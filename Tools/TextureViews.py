#!/usr/bin/env python3
"""Generate the texture-view binding registry from owned HLSL declarations. No asset-load hooks."""
from pathlib import Path
import re
import sys
ROOT = Path(__file__).resolve().parent.parent
DECL = re.compile(r'^\s*(?:RW)?Texture(2DArray|2D|3D)(?:<[^>]+>)?\s+(\w+)\s*;', re.M)
def sources():
    for directory in ('Shaders', 'Editor/ShaderGraph/Includes'):
        for p in (ROOT / directory).rglob('*'):
            if p.name.startswith('._') or p.suffix not in ('.hlsl','.compute','.shader'): continue
            if p.name in ('TextureViews.generated.hlsl',): continue
            yield p

def outputs():
    names = sorted({name for p in sources() for _,name in DECL.findall(p.read_text())})
    hlsl = '// Generated by Tools/TextureViews.py from owned texture declarations.\n'
    hlsl += '#ifndef INFINITY_TEXTURE_VIEW_BINDINGS\n#define INFINITY_TEXTURE_VIEW_BINDINGS\n'
    hlsl += ''.join('float4 ' + name + '_InfinityView;\n' for name in names) + '#endif\n'
    cs = '''// Generated by Tools/TextureViews.py from owned texture declarations.
using System.Collections.Generic;
using UnityEngine;
namespace InfinityTech.Rendering.RenderGraph
{
    internal static partial class TextureViewBindings
    {
        static readonly Dictionary<int,int> s_ViewIDs = new Dictionary<int,int>
        {
'''
    cs += ''.join('            { Shader.PropertyToID("'+n+'"), Shader.PropertyToID("'+n+'_InfinityView") },\n' for n in names)
    cs += '        };\n    }\n}\n'
    return {ROOT/'Shaders/ShaderLibrary/TextureViews.generated.hlsl':hlsl,ROOT/'Runtime/RendererCore/RenderGraph/TextureViewBindings.generated.cs':cs}

def main():
    failed = False
    for path,text in outputs().items():
        if '--write' in sys.argv: path.write_text(text)
        elif not path.exists() or path.read_text() != text:
            print('Stale texture-view binding registry:',path.relative_to(ROOT)); failed = True
    return int(failed)
if __name__ == '__main__': sys.exit(main())
